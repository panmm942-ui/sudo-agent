"""Intent fixtures -> OpenAI function-calling tool schemas."""

from __future__ import annotations

SYSTEM_PROMPT = (
    "You are sudo, a fast desktop assistant. Pick exactly one tool for the user's request. "
    "Users speak English or Greek. "
    "Use chat for questions you can answer yourself or small talk; "
    "use web_search only when the user asks to search or look something up. "
    # Measured on Qwen3.5-4B: without this it answers chat requests in plain text first and runs to max_tokens.
    "Never write a reply yourself: respond only with a tool call (chat takes no arguments)."
)


def tool_name(intent_id: str) -> str:
    """Intent ids use dots (`media.next`); LLM tool names use underscores."""
    return intent_id.replace(".", "_")


def intents_to_tools(intents: dict) -> list[dict]:
    """Build the tool list. Order follows `intents`; keep it stable so the prompt cache stays valid.

    No `required` lists: every parameter is optional. `chat` takes no parameters: the reply is
    generated by a separate call after the tool is chosen, never inside the tool call.
    """
    tools: list[dict] = []
    for intent_id, spec in intents.items():
        props = dict(spec.get("params") or {})
        tools.append(
            {
                "type": "function",
                "function": {
                    "name": tool_name(intent_id),
                    "description": spec["en"],
                    "parameters": {"type": "object", "properties": props},
                },
            }
        )
    return tools
